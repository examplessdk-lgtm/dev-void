import { describe, expect, it } from 'vite-plus/test';
import { generateQueueTypes } from '../../src/codegen/queue-types.ts';

describe('generateQueueTypes', () => {
  it('generates queue type declarations with payload extraction', () => {
    const queues = [{ filePath: 'emails.ts', name: 'emails', bindingName: 'QUEUE_EMAILS' }];

    const result = generateQueueTypes(queues, '/project/queues', '/project/.void');
    expect(result).toContain('// Auto-generated by void');
    expect(result).toContain('export interface QueueMap');
    expect(result).toContain('"emails": Queue<');
    expect(result).toContain('import("../queues/emails.ts")');
    expect(result).toContain('["default"]["__payload"]');
    expect(result).toContain('export declare const queues: QueueMap;');
  });

  it('handles multiple queues', () => {
    const queues = [
      { filePath: 'emails.ts', name: 'emails', bindingName: 'QUEUE_EMAILS' },
      {
        filePath: 'order/notifications.ts',
        name: 'order-notifications',
        bindingName: 'QUEUE_ORDER_NOTIFICATIONS',
      },
    ];

    const result = generateQueueTypes(queues, '/project/queues', '/project/.void');
    expect(result).toContain('"emails": Queue<');
    expect(result).toContain('"order-notifications": Queue<');
    expect(result).toContain('import("../queues/order/notifications.ts")');
  });

  it('generates empty declaration for no queues', () => {
    const result = generateQueueTypes([], '/project/queues', '/project/.void');
    expect(result).toContain('interface QueueMap {');
    expect(result).toContain('}');
    expect(result).not.toContain('Queue<');
  });
});
