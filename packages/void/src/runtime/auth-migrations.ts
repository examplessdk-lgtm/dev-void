import type {
  VoidAuthMigrationField,
  VoidAuthMigrationSchema,
  VoidAuthMigrationTable,
} from '../auth/drizzle.ts';

export type SqliteMigrationRunner = {
  all<T extends Record<string, unknown> = Record<string, unknown>>(sql: string): Promise<Array<T>>;
  run(sql: string): Promise<void>;
};

/** PostgreSQL and MySQL runners accept bound parameters. */
export type ParameterizedMigrationRunner = {
  all<T extends Record<string, unknown> = Record<string, unknown>>(
    sql: string,
    params?: Array<unknown>,
  ): Promise<Array<T>>;
  run(sql: string, params?: Array<unknown>): Promise<void>;
};

function quoteIdentifier(name: string, dialect: VoidAuthMigrationSchema['dialect']): string {
  return dialect === 'mysql'
    ? `\`${name.replaceAll('`', '``')}\``
    : `"${name.replaceAll('"', '""')}"`;
}

function quotePragmaArg(name: string): string {
  return `'${name.replaceAll("'", "''")}'`;
}

function createIndexName(tableName: string, fieldName: string, unique: boolean): string {
  return `${tableName}_${fieldName}_${unique ? 'uidx' : 'idx'}`;
}

function resolveColumnType(
  dialect: 'sqlite' | 'postgresql' | 'mysql',
  idStrategy: VoidAuthMigrationSchema['idStrategy'],
  fieldName: string,
  field: VoidAuthMigrationField,
): string {
  const useIdType = fieldName === 'id' || field.references?.field === 'id';

  if (dialect === 'mysql') {
    if (useIdType) {
      if (fieldName === 'id' && idStrategy === 'serial') {
        return 'int AUTO_INCREMENT';
      }
      return idStrategy === 'serial'
        ? 'int'
        : idStrategy === 'uuid'
          ? 'varchar(36)'
          : 'varchar(255)';
    }
    if (field.type === 'boolean') {
      return 'boolean';
    }
    if (field.type === 'date') {
      return 'datetime(3)';
    }
    if (field.type === 'number') {
      return field.bigint ? 'bigint' : 'int';
    }
    if (field.type === 'json' || field.type === 'string[]' || field.type === 'number[]') {
      return 'json';
    }
    return field.unbounded ? 'text' : 'varchar(255)';
  }

  if (dialect === 'postgresql') {
    if (useIdType) {
      if (fieldName === 'id' && idStrategy === 'serial') {
        return 'integer GENERATED BY DEFAULT AS IDENTITY';
      }
      if (idStrategy === 'serial') {
        return 'integer';
      }
      if (idStrategy === 'uuid') {
        return 'uuid';
      }
      return 'text';
    }
    if (field.type === 'boolean') {
      return 'boolean';
    }
    if (field.type === 'date') {
      return 'timestamptz';
    }
    if (field.type === 'number') {
      return field.bigint ? 'bigint' : 'integer';
    }
    if (field.type === 'json' || field.type === 'string[]' || field.type === 'number[]') {
      return 'jsonb';
    }
    return 'text';
  }

  if (useIdType) {
    return idStrategy === 'serial' ? 'INTEGER' : 'TEXT';
  }
  if (field.type === 'boolean' || field.type === 'date' || field.type === 'number') {
    return 'INTEGER';
  }
  return 'TEXT';
}

function buildColumnDefinition(
  dialect: 'sqlite' | 'postgresql' | 'mysql',
  schema: VoidAuthMigrationSchema,
  fieldName: string,
  field: VoidAuthMigrationField,
  options: { primaryKey?: boolean } = {},
): string {
  const parts = [
    `${quoteIdentifier(fieldName, dialect)} ${resolveColumnType(dialect, schema.idStrategy, fieldName, field)}`,
  ];

  if (options.primaryKey) {
    parts.push('PRIMARY KEY');
  }
  if (field.required || options.primaryKey) {
    parts.push('NOT NULL');
  }
  if (field.references) {
    parts.push(
      `REFERENCES ${quoteIdentifier(field.references.table, dialect)}(${quoteIdentifier(
        field.references.field,
        dialect,
      )}) ON DELETE ${String(field.references.onDelete ?? 'cascade').toUpperCase()}`,
    );
  }

  return parts.join(' ');
}

function buildCreateTableSql(
  schema: VoidAuthMigrationSchema,
  table: VoidAuthMigrationTable,
): string {
  const dialect = schema.dialect;
  const columns = [
    buildColumnDefinition(
      dialect,
      schema,
      'id',
      {
        type: schema.idStrategy === 'serial' ? 'number' : 'string',
        required: true,
        unique: false,
        index: false,
        bigint: false,
      },
      { primaryKey: true },
    ),
    ...Object.entries(table.fields).map(([fieldName, field]) =>
      buildColumnDefinition(dialect, schema, fieldName, field),
    ),
  ];

  return `CREATE TABLE IF NOT EXISTS ${quoteIdentifier(table.name, dialect)} (${columns.join(', ')})`;
}

function buildAddColumnSql(
  schema: VoidAuthMigrationSchema,
  tableName: string,
  fieldName: string,
  field: VoidAuthMigrationField,
): string {
  const ifNotExists = schema.dialect === 'sqlite' ? '' : ' IF NOT EXISTS';
  return `ALTER TABLE ${quoteIdentifier(tableName, schema.dialect)} ADD COLUMN${ifNotExists} ${buildColumnDefinition(
    schema.dialect,
    schema,
    fieldName,
    field,
  )}`;
}

function buildModifyMySqlColumnSql(
  schema: VoidAuthMigrationSchema,
  tableName: string,
  fieldName: string,
  field: VoidAuthMigrationField,
): string {
  return `ALTER TABLE ${quoteIdentifier(tableName, 'mysql')} MODIFY COLUMN ${buildColumnDefinition(
    'mysql',
    schema,
    fieldName,
    field,
  )}`;
}

function buildCreateIndexSql(
  dialect: VoidAuthMigrationSchema['dialect'],
  tableName: string,
  fieldName: string,
  unique: boolean,
): string {
  return `CREATE ${unique ? 'UNIQUE ' : ''}INDEX${dialect === 'mysql' ? '' : ' IF NOT EXISTS'} ${quoteIdentifier(
    createIndexName(tableName, fieldName, unique),
    dialect,
  )} ON ${quoteIdentifier(tableName, dialect)} (${quoteIdentifier(fieldName, dialect)})`;
}

async function createMissingIndexes(
  runner: { run(sql: string): Promise<void> },
  dialect: VoidAuthMigrationSchema['dialect'],
  table: VoidAuthMigrationTable,
  existingIndexes: ReadonlySet<string>,
): Promise<void> {
  for (const [fieldName, field] of Object.entries(table.fields)) {
    if (!field.index && !field.unique) {
      continue;
    }
    const indexName = createIndexName(table.name, fieldName, field.unique);
    if (existingIndexes.has(indexName)) {
      continue;
    }
    await runner.run(buildCreateIndexSql(dialect, table.name, fieldName, field.unique));
  }
}

async function ensureSqliteIndexes(
  runner: SqliteMigrationRunner,
  table: VoidAuthMigrationTable,
): Promise<void> {
  const indexRows = await runner.all<{ name?: string }>(
    `PRAGMA index_list(${quotePragmaArg(table.name)})`,
  );
  const existingIndexes = new Set(indexRows.map((row) => String(row.name)));
  await createMissingIndexes(runner, 'sqlite', table, existingIndexes);
}

async function ensurePgIndexes(
  runner: ParameterizedMigrationRunner,
  schemaName: string,
  table: VoidAuthMigrationTable,
): Promise<void> {
  const indexRows = await runner.all<{ indexname?: string }>(
    'SELECT indexname FROM pg_indexes WHERE schemaname = $1 AND tablename = $2',
    [schemaName, table.name],
  );
  const existingIndexes = new Set(indexRows.map((row) => String(row.indexname)));
  await createMissingIndexes(runner, 'postgresql', table, existingIndexes);
}

export async function applySqliteAuthMigrations(
  runner: SqliteMigrationRunner,
  schema: VoidAuthMigrationSchema,
): Promise<void> {
  const tableRows = await runner.all<{ name?: string }>(
    "SELECT name FROM sqlite_master WHERE type = 'table'",
  );
  const existingTables = new Set(tableRows.map((row) => String(row.name)));

  for (const table of schema.tables) {
    if (!existingTables.has(table.name)) {
      await runner.run(buildCreateTableSql(schema, table));
      await ensureSqliteIndexes(runner, table);
      existingTables.add(table.name);
      continue;
    }

    const columnRows = await runner.all<{ name?: string }>(
      `PRAGMA table_info(${quotePragmaArg(table.name)})`,
    );
    const existingColumns = new Set(columnRows.map((row) => String(row.name)));

    for (const [fieldName, field] of Object.entries(table.fields)) {
      if (existingColumns.has(fieldName)) {
        continue;
      }
      await runner.run(buildAddColumnSql(schema, table.name, fieldName, field));
    }

    await ensureSqliteIndexes(runner, table);
  }
}

export async function applyPgAuthMigrations(
  runner: ParameterizedMigrationRunner,
  schema: VoidAuthMigrationSchema,
): Promise<void> {
  const schemaRows = await runner.all<{ schema?: string }>('SELECT current_schema() AS schema');
  const schemaName = String(schemaRows[0]?.schema ?? 'public');
  const tableRows = await runner.all<{ table_name?: string }>(
    "SELECT table_name FROM information_schema.tables WHERE table_schema = $1 AND table_type = 'BASE TABLE'",
    [schemaName],
  );
  const existingTables = new Set(tableRows.map((row) => String(row.table_name)));

  for (const table of schema.tables) {
    if (!existingTables.has(table.name)) {
      await runner.run(buildCreateTableSql(schema, table));
      await ensurePgIndexes(runner, schemaName, table);
      existingTables.add(table.name);
      continue;
    }

    const columnRows = await runner.all<{ column_name?: string }>(
      'SELECT column_name FROM information_schema.columns WHERE table_schema = $1 AND table_name = $2',
      [schemaName, table.name],
    );
    const existingColumns = new Set(columnRows.map((row) => String(row.column_name)));

    for (const [fieldName, field] of Object.entries(table.fields)) {
      if (existingColumns.has(fieldName)) {
        continue;
      }
      await runner.run(buildAddColumnSql(schema, table.name, fieldName, field));
    }

    await ensurePgIndexes(runner, schemaName, table);
  }
}

export async function applyMySqlAuthMigrations(
  runner: ParameterizedMigrationRunner,
  schema: VoidAuthMigrationSchema,
): Promise<void> {
  const databaseRows = await runner.all<{ database_name?: string }>(
    'SELECT DATABASE() AS database_name',
  );
  const databaseName = String(databaseRows[0]?.database_name ?? '');
  const tableRows = await runner.all<{ table_name?: string }>(
    "SELECT table_name FROM information_schema.tables WHERE table_schema = ? AND table_type = 'BASE TABLE'",
    [databaseName],
  );
  const existingTables = new Set(tableRows.map((row) => String(row.table_name)));

  for (const table of schema.tables) {
    if (!existingTables.has(table.name)) {
      await runner.run(buildCreateTableSql(schema, table));
      existingTables.add(table.name);
    } else {
      const columnRows = await runner.all<{
        column_name?: string;
        data_type?: string;
        character_maximum_length?: number | string | null;
      }>(
        'SELECT column_name, data_type, character_maximum_length FROM information_schema.columns WHERE table_schema = ? AND table_name = ?',
        [databaseName, table.name],
      );
      const existingColumns = new Map(
        columnRows.map((row) => [String(row.column_name), row] as const),
      );
      for (const [fieldName, field] of Object.entries(table.fields)) {
        const existingColumn = existingColumns.get(fieldName);
        if (!existingColumn) {
          await runner.run(buildAddColumnSql(schema, table.name, fieldName, field));
        } else if (
          field.unbounded &&
          String(existingColumn.data_type ?? '').toLowerCase() === 'varchar'
        ) {
          await runner.run(buildModifyMySqlColumnSql(schema, table.name, fieldName, field));
        }
      }
    }

    const indexRows = await runner.all<{ index_name?: string }>(
      'SELECT index_name FROM information_schema.statistics WHERE table_schema = ? AND table_name = ?',
      [databaseName, table.name],
    );
    const existingIndexes = new Set(indexRows.map((row) => String(row.index_name)));
    await createMissingIndexes(runner, 'mysql', table, existingIndexes);
  }
}
