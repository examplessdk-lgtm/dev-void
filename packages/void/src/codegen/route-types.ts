import { relative } from "node:path";
import type { ScanResult } from "../router/scan";

export interface RouteTypesResult {
  dts: string;
}

/**
 * Generate .void/routes.d.ts content.
 *
 * Uses `typeof import(...)` so TypeScript resolves all types.
 * The codegen generates scaffolding only — never analyzes types itself.
 */
export function generateRouteTypes(
  scan: ScanResult,
  routesDir: string,
  outDir: string,
  pagesDir?: string,
): RouteTypesResult {
  const lines: string[] = [];

  lines.push("// Auto-generated by void — do not edit");
  // Inline the Standard Schema types so the generated file is self-contained
  // (no external dependency on @standard-schema/spec)
  lines.push("interface StandardSchemaV1<Input = unknown, Output = Input> {");
  lines.push('  readonly "~standard": {');
  lines.push("    readonly version: 1;");
  lines.push("    readonly vendor: string;");
  lines.push("    readonly validate: (value: unknown) => unknown;");
  lines.push(
    "    readonly types?: { readonly input: Input; readonly output: Output } | undefined;",
  );
  lines.push("  };");
  lines.push("}");
  lines.push("declare namespace StandardSchemaV1 {");
  lines.push("  type InferInput<Schema extends StandardSchemaV1> = NonNullable<");
  lines.push('    Schema["~standard"]["types"]');
  lines.push('  >["input"];');
  lines.push("}");
  lines.push("");
  lines.push("type Serialize<T> =");
  lines.push("  T extends Response ? never :");
  lines.push("  T extends Date ? string :");
  lines.push("  T extends bigint ? never :");
  lines.push("  T extends Function ? never :");
  lines.push("  T extends undefined ? never :");
  lines.push("  T extends Array<infer U> ? Array<Serialize<U>> :");
  lines.push(
    "  T extends object ? { [K in keyof T as T[K] extends Function ? never : K]: Serialize<T[K]> } :",
  );
  lines.push("  T;");
  lines.push("");

  // Helper type to extract validated input from __validators
  lines.push("type ExtractInput<V> = {");
  lines.push("  [K in keyof V as V[K] extends StandardSchemaV1 ? K : never]:");
  lines.push("    V[K] extends StandardSchemaV1 ? StandardSchemaV1.InferInput<V[K]> : never;");
  lines.push("};");
  lines.push("");

  lines.push('declare module "void/routes" {');
  lines.push("  interface RouteMap {");

  for (const route of scan.routes) {
    if (route.methods.length === 0) continue;

    // Compute relative path from outDir (.void/) to the route file
    const absRoutePath = `${routesDir}/${route.filePath}`;
    const relPath = relative(outDir, absRoutePath).replace(/\\/g, "/");
    // Strip extension for TypeScript import
    const importPath = relPath.replace(/\.(ts|mts|js|mjs)$/, "");

    lines.push(`    ${JSON.stringify(route.pattern)}: {`);

    for (const method of route.methods) {
      lines.push(`      ${method}: {`);
      lines.push(
        `        input: ExtractInput<(typeof import(${JSON.stringify(importPath)}))["${method}"]["__validators"]>;`,
      );
      lines.push(
        `        output: Serialize<Awaited<(typeof import(${JSON.stringify(importPath)}))["${method}"]["__output"]>>;`,
      );
      lines.push("      };");
    }

    lines.push("    };");
  }

  lines.push("  }");

  // PageActionMap — page actions for typed useForm
  const actionPages = scan.pages.pages.filter(
    (p) => p.methods.includes("action") || p.methods.includes("actions"),
  );
  if (actionPages.length > 0 && pagesDir) {
    lines.push("  interface PageActionMap {");

    for (const page of actionPages) {
      const hasAction = page.methods.includes("action");
      const hasActions = page.methods.includes("actions");

      if (hasAction && hasActions) {
        throw new Error(
          `Page "${page.pattern}" exports both "action" and "actions". Use one or the other.`,
        );
      }

      lines.push(`    ${JSON.stringify(page.pattern)}: {`);

      let importPath: string | null = null;

      if (page.serverPath) {
        // Companion .server.ts — resolve directly
        const absPath = `${pagesDir}/${page.serverPath}`;
        const rel = relative(outDir, absPath).replace(/\\/g, "/");
        importPath = rel.replace(/\.(ts|mts|js|mjs)$/, "");
      }

      if (hasActions) {
        if (importPath) {
          const actionsImport = `(typeof import(${JSON.stringify(importPath)}))["actions"]`;
          lines.push(`      actions: { [K in keyof ${actionsImport}]: {`);
          lines.push(
            `        body: ExtractInput<${actionsImport}[K]["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
          );
          lines.push("      } };");
        }
      } else if (importPath) {
        const importExpr = `(typeof import(${JSON.stringify(importPath)}))["action"]`;
        lines.push(
          `      body: ExtractInput<${importExpr}["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
        );
      } else {
        lines.push("      body: Record<string, unknown>;");
      }

      if (page.params.length > 0) {
        const paramsType = page.params.map((p) => `${p}: string`).join("; ");
        lines.push(`      params: { ${paramsType} };`);
      }

      lines.push("    };");
    }

    lines.push("  }");
  }

  lines.push("}");
  lines.push("");

  return { dts: lines.join("\n") };
}
