import { relative } from 'pathslash';
import type { QueueDefinition } from '../queues/scan.ts';

/**
 * Generate .void/queues.d.ts content.
 *
 * Augments `void/queues` with a typed `QueueMap` interface
 * so `queues.emails.send(body)` is fully typed from the consumer's
 * `defineQueue<T>` phantom type.
 */
export function generateQueueTypes(
  queues: Array<QueueDefinition>,
  queuesDir: string,
  outDir: string,
): string {
  const lines: Array<string> = [];
  lines.push('// Auto-generated by void — do not edit');
  lines.push('export interface QueueMap {');

  for (const q of queues) {
    const absPath = `${queuesDir}/${q.filePath}`;
    const importPath = relative(outDir, absPath);

    lines.push(
      `  ${JSON.stringify(q.name)}: Queue<(typeof import(${JSON.stringify(importPath)}))["default"]["__payload"]>;`,
    );
  }

  lines.push('}');
  lines.push('');
  lines.push('export declare const queues: QueueMap;');
  lines.push('');
  return lines.join('\n');
}
