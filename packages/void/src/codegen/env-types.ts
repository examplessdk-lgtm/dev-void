import { existsSync } from 'node:fs';
import { relative } from 'pathslash';
import { voidWarn } from '../log.ts';
import { readProjectPaths, type ProjectPaths } from '../project-paths.ts';

/** Roots already warned about duplicate env.ts files — dedupes noisy repeat calls. */
const warnedRoots = new Set<string>();

/** Find the user's env schema file, if any. Warns once per root when multiple candidates exist. */
export function findEnvFile(root: string): string | null {
  return findEnvFileForPaths(root, readProjectPaths(root));
}

export function findEnvFileForPaths(root: string, paths: ProjectPaths): string | null {
  const matches: Array<string> = [];
  for (const absPath of paths.envFileCandidates) {
    if (existsSync(absPath)) {
      matches.push(absPath);
    }
  }
  if (matches.length > 1 && !warnedRoots.has(root)) {
    warnedRoots.add(root);
    const rel = matches.map((m) => relative(root, m));
    voidWarn(
      `Multiple env schema files found — using "${rel[0]}" and ignoring ${rel
        .slice(1)
        .map((r) => `"${r}"`)
        .join(', ')}. Keep just one.`,
    );
  }
  return matches[0] ?? null;
}

export type EnvTypesResult = {
  dts: string;
};

/**
 * Generate `.void/env.d.ts` content. Augments:
 *   - `void/env`'s `ValidatedEnv` so `env.X` is typed
 *   - `void/handler`'s `CloudBindings` so `c.env.X` is typed
 *
 * Uses `typeof import(...)` on the env schema file so TypeScript handles the
 * inference — codegen never analyses types itself.
 *
 * @param envFileAbs Absolute path to the user's env schema file.
 * @param outDir Absolute path to the project's `.void/` directory.
 */
export function generateEnvTypes(envFileAbs: string, outDir: string): EnvTypesResult {
  const importPath = relative(outDir, envFileAbs);
  const lines: Array<string> = [];

  lines.push('// Auto-generated by void — do not edit');
  // Top-level export makes this a module so `declare module` augments
  // (rather than replaces) void/env and void/handler.
  lines.push('export {}');
  lines.push('');
  lines.push(`type _VoidEnvSchema = typeof import("${importPath}");`);
  // The user's env.ts may either `export default defineEnv({...})` or
  // `export const env = defineEnv({...})`. Both return the typed `env` proxy;
  // using either export here gives us the inferred shape directly — no schema
  // introspection required.
  lines.push(
    'type _VoidEnvShape = _VoidEnvSchema extends { default: infer D } ? D : _VoidEnvSchema extends { env: infer E } ? E : {};',
  );
  lines.push('');
  lines.push('declare module "void/env" {');
  lines.push('  interface ValidatedEnv extends _VoidEnvShape {}');
  lines.push('}');
  lines.push('');
  lines.push('declare global {');
  lines.push('  interface VoidGeneratedEnvBindings extends _VoidEnvShape {}');
  lines.push('}');
  lines.push('');
  // Augment Hono c.env via the CloudBindings interface re-exported from void/handler.
  lines.push('declare module "void/handler" {');
  lines.push('  interface CloudBindings extends _VoidEnvShape {}');
  lines.push('}');
  lines.push('');

  return { dts: lines.join('\n') };
}
