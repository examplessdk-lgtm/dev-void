import { existsSync } from 'node:fs';
import { join, relative } from 'pathe';

/** Possible source locations for the user env schema, in priority order. */
export const ENV_FILE_CANDIDATES = ['env.ts', 'env.mts', 'env.js', 'env.mjs'] as const;

/** Find the user's env schema file, if any. */
export function findEnvFile(root: string): string | null {
  for (const candidate of ENV_FILE_CANDIDATES) {
    const abs = join(root, candidate);
    if (existsSync(abs)) {
      return abs;
    }
  }
  return null;
}

export interface EnvTypesResult {
  dts: string;
}

/**
 * Generate `.void/env.d.ts` content. Augments:
 *   - `void/env`'s `ValidatedEnv` so `env.X` is typed
 *   - `void/handler`'s `CloudBindings` so `c.env.X` is typed
 *
 * Uses `typeof import("../env").default` so TypeScript handles the
 * inference — codegen never analyses types itself.
 *
 * @param envFileAbs Absolute path to the user's env schema file.
 * @param outDir Absolute path to the project's `.void/` directory.
 */
export function generateEnvTypes(envFileAbs: string, outDir: string): EnvTypesResult {
  const rel = relative(outDir, envFileAbs).replace(/\\/g, '/');
  // Strip extension so resolution works for both .ts and .mts sources.
  const importPath = rel.replace(/\.(ts|mts|js|mjs)$/, '');
  const lines: string[] = [];

  lines.push('// Auto-generated by void — do not edit');
  // Top-level export makes this a module so `declare module` augments
  // (rather than replaces) void/env and void/handler.
  lines.push('export {}');
  lines.push('');
  lines.push(`type _VoidEnvSchema = typeof import("${importPath}");`);
  // The user's env.ts default-exports `defineEnv({...})`, which returns the
  // typed `env` proxy. Using `default` here gives us the inferred shape
  // directly — no schema introspection required.
  lines.push('type _VoidEnvShape = _VoidEnvSchema extends { default: infer D } ? D : {};');
  lines.push('');
  lines.push('declare module "void/env" {');
  lines.push('  interface ValidatedEnv extends _VoidEnvShape {}');
  lines.push('}');
  lines.push('');
  // Augment Hono c.env via the CloudBindings interface re-exported from void/handler.
  lines.push('declare module "void/handler" {');
  lines.push('  interface CloudBindings extends _VoidEnvShape {}');
  lines.push('}');
  lines.push('');

  return { dts: lines.join('\n') };
}
