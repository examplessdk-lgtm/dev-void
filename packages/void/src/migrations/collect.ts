import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Collect all .sql migration files from the migrations directory,
 * sorted by filename (lexicographic order).
 */
export function collectMigrations(migrationsDir: string): { name: string; sql: string }[] {
  if (!existsSync(migrationsDir)) {
    return [];
  }

  return readdirSync(migrationsDir)
    .filter((f) => f.endsWith('.sql') && f !== 'seed.sql')
    .sort()
    .map((name) => ({
      name,
      sql: readFileSync(join(migrationsDir, name), 'utf-8'),
    }));
}

/**
 * When a Drizzle `_journal.json` exists, validate that every `.sql` file
 * in the migrations directory is tracked by the journal. Orphan files
 * (present on disk but missing from the journal) cause duplicate-migration
 * failures on deploy.
 *
 * Does nothing when no `_journal.json` exists (manual-only project).
 */
export function validateJournalCoherence(migrationsDir: string): void {
  const journalPath = join(migrationsDir, 'meta', '_journal.json');
  if (!existsSync(journalPath)) {
    return;
  }

  let journal: { entries?: { tag?: string }[] };
  try {
    journal = JSON.parse(readFileSync(journalPath, 'utf-8'));
  } catch {
    return; // Malformed journal — let drizzle-kit handle it
  }

  const trackedFiles = new Set(
    (journal.entries ?? []).filter((e) => typeof e.tag === 'string').map((e) => `${e.tag}.sql`),
  );

  const diskFiles = readdirSync(migrationsDir).filter(
    (f) => f.endsWith('.sql') && f !== 'seed.sql',
  );

  const orphans = diskFiles.filter((f) => !trackedFiles.has(f));
  if (orphans.length === 0) {
    return;
  }

  throw new Error(
    `Found migration file(s) not tracked in db/migrations/meta/_journal.json:\n` +
      orphans.map((f) => `  - ${f}`).join('\n') +
      `\n\nThese files were not generated by \`void db generate\` and will conflict ` +
      `with Drizzle-managed migrations.\n` +
      `Either remove them or re-generate migrations with \`void db generate\`.`,
  );
}
